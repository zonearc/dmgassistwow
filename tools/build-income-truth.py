#!/usr/bin/env python3
"""Passive income per spec from the resource truth (data/resource-truth/*.json, tools/wcl-truth.py).

Between two casts of a top player, the true amount moved by: what the first cast cost and listed gain (our data),
regeneration (Energy 10/s, Focus 5/s with 25% raid haste), and everything else: auto-attack Rage, Runic Power from
runes, procs, damage-over-time ticks. That "everything else" a second, the median over the fights, is the spec's
passive income. Our data's own figure for it was 2-10 times too low for Fury, Outlaw, the Death Knights and Arms,
and too high for Devourer and Survival (2026-11-21), so the addon's counts ran far from the truth.

Writes addons/DMGAssist/Data/IncomeTruth.lua.
Usage: python3 tools/build-income-truth.py
"""
import glob
import json
import os
import re
import statistics

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TRUTH = os.path.join(ROOT, "data", "resource-truth")
DATA = os.path.join(ROOT, "addons", "DMGAssist", "Data", "midnight")
OUT = os.path.join(ROOT, "addons", "DMGAssist", "Data", "IncomeTruth.lua")

SCALE = {1: 10, 6: 10, 7: 10, 8: 10, 13: 100}  # Warcraft Logs' units -> the game's
REGEN = {3: 10 * 1.25, 2: 5 * 1.25}
SKIP = {0, 4, 5, 7, 9, 12, 19}  # mana (own model), points the game shows, runes (recharge model)
# Held back: with the measured income the graded simulator's slot 2 got worse for these (Fury 80 -> 50%, Blood
# 86 -> 72%, Frost 74 -> 67%, Guardian 88 -> 86%, Survival 92 -> 72% in the simple fights, no graded reference) while the owner found Fury fine in game (2026-11-21). They keep
# the data's figure until the cause is found (tracked in docs/project/tasks.md).
HOLD = {"warrior_fury", "deathknight_blood", "deathknight_frost", "druid_guardian", "hunter_survival"}


def spell_gains(spec):
    with open(os.path.join(DATA, spec + ".lua"), encoding="utf-8") as f:
        text = f.read()
    gains = {}
    for m in re.finditer(r"\[(\d+)\] = \{(.*?)\n    \},", text, re.S):
        g = re.search(r"gain = \{([^}]*)\}", m.group(2))
        if g:
            gains[int(m.group(1))] = {int(a): float(b) for a, b in re.findall(r"\[(\d+)\] = ([\d.]+)", g.group(1))}
    return gains


def regen_auras(spec):
    """Spells whose aura speeds regeneration (data "rgp"): id -> (duration, {pt: percent})."""
    with open(os.path.join(DATA, spec + ".lua"), encoding="utf-8") as f:
        text = f.read()
    out = {}
    for m in re.finditer(r"\[(\d+)\] = \{(.*?)\n    \},", text, re.S):
        r = re.search(r"rgp = \{([^}]*)\}", m.group(2))
        d = re.search(r"\n      d = ([\d.]+)", m.group(2))
        if r and d:
            out[int(m.group(1))] = (float(d.group(1)),
                                    {int(a): float(b) for a, b in re.findall(r"\[(\d+)\] = (-?[\d.]+)", r.group(1))})
    return out


def income(spec, fights):
    gains = spell_gains(spec)
    boosts = regen_auras(spec)
    rates = {}
    for f in fights:
        for spt, mx in f["max"].items():
            pt = int(spt)
            if pt in SKIP:
                continue
            sc = SCALE.get(pt, 1)
            mx = mx / sc
            pts = [(t, h[spt] / sc, c.get(spt, 0) / sc, sid) for t, sid, h, c in f["casts"] if spt in h]
            # (regeneration boosted while one of our auras is up: Adrenaline Rush - the addon applies it itself)
            ups = [(t, t + boosts[sid][0], boosts[sid][1].get(pt, 0)) for t, sid, _, _ in f["casts"] if sid in boosts]
            num = den = 0.0
            for (t1, a1, c1, s1), (t2, a2, _, _) in zip(pts, pts[1:]):
                dt = t2 - t1
                if 0.2 < dt < 6 and a2 < mx * 0.95:  # (not capped: nothing was lost to the cap)
                    mult = 1 + sum(p for a, b, p in ups if a <= t1 < b) / 100.0
                    num += a2 - a1 + c1 - gains.get(s1, {}).get(pt, 0) - REGEN.get(pt, 0) * mult * dt
                    den += dt
            if den > 20:
                rates.setdefault(pt, []).append(num / den)
    return {pt: max(0.0, statistics.median(v)) for pt, v in rates.items()}


def main():
    rows = []
    for path in sorted(glob.glob(os.path.join(TRUTH, "*.json"))):
        spec = os.path.basename(path)[:-5]
        if spec in HOLD:
            continue
        with open(path, encoding="utf-8") as f:
            fights = json.load(f)
        r = income(spec, fights)
        if r:
            parts = ", ".join("[%d] = %.2f" % (pt, v) for pt, v in sorted(r.items()))
            rows.append("  %s = { %s }," % (spec, parts))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("-- Generated by tools/build-income-truth.py from top players' fights on Warcraft Logs (true resource\n"
                "-- values at every cast). Do not edit: measure again and rebuild. Per spec: power type -> income a\n"
                "-- second beyond regeneration and what each cast lists (auto-attack Rage, procs, ticks).\n"
                "local _, ns = ...\nns.Data = ns.Data or {}\nns.Data.incomeTruth = {\n")
        f.write("\n".join(rows) + "\n}\n")
    print("wrote", OUT, len(rows), "specs")


if __name__ == "__main__":
    main()
