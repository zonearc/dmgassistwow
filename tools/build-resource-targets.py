#!/usr/bin/env python3
"""Build addons/DMGAssist/Data/ResourceTargets.lua: per spec and number of targets, the income a second with no cast
of its own, from two measurements:

  - data/resource-income.json (tools/wcl-income.py): total income from the casts' logged amounts - everything,
    auto-attack Rage included (not logged as gain events). Income a second = the data's passive income + what the
    real total has beyond what our data accounts for. Preferred where present ("raid" fights count as 1 target);
  - data/resource-targets.json (tools/wcl-targets.py): income events not caused by a cast of the player's.

SKIP lists measurements known to be wrong.
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "addons", "DMGAssist", "Data", "ResourceTargets.lua")
POWER = {"druid_balance": 8, "druid_guardian": 1, "warrior_arms": 1, "warrior_fury": 1, "warrior_protection": 1,
         "deathknight_blood": 6, "deathknight_frost": 6, "deathknight_unholy": 6, "demonhunter_havoc": 17,
         "demonhunter_vengeance": 17, "demonhunter_devourer": 17, "priest_shadow": 13, "shaman_elemental": 11}
# event-based measurements that don't hold: Arms' Rage comes from auto-attacks, not logged as gains (0.12/s on 5)
TANKS = {"druid_guardian", "warrior_protection", "deathknight_blood", "demonhunter_vengeance", "monk_brewmaster"}
SKIP_EVENTS = {"warrior_arms", "warrior_fury", "warrior_protection", "druid_guardian"}  # (Rage: auto-attacks, damage taken)


def load(name):
    p = os.path.join(ROOT, "data", name)
    return json.load(open(p)) if os.path.exists(p) else {}


def main():
    gains = load("resource-gains.json").get("midnight", {})
    events = load("resource-targets.json")
    income = load("resource-income.json")
    table = {}
    for spec, by in events.items():
        if spec in SKIP_EVENTS or spec not in POWER:
            continue
        for n, r in by.items():
            if r.get("seconds", 0) >= 200 and r.get("perSecond"):
                table.setdefault(spec, {})[int(n)] = sum(v["rate"] for v in r["perSecond"].values())
    for spec, by in income.items():
        pt = POWER.get(spec)
        if pt is None:
            continue
        base = float(gains.get(spec, {}).get("passive", {}).get(str(pt), 0))
        rows = {}
        for n, r in by.items():
            if r.get("seconds", 0) < 200:
                continue
            k = 1 if n == "raid" else int(n)
            # tanks: one target from raid fights (Rage / Runic Power / Fury from being hit, which dummies don't do -
            # Guardian 7/s on a dummy, 19/s on a boss); everyone else from the dummy when there is one
            usable1 = "1" in by and by["1"].get("seconds", 0) >= 200
            if n == "raid" and usable1 and spec not in TANKS:
                continue
            if n == "1" and "raid" in by and spec in TANKS:
                continue
            rows[k] = max(0.0, base + r["income"] - r["model"])
        if rows:
            table[spec] = rows
    lines = ["-- Generated by tools/build-resource-targets.py from Warcraft Logs (Dummy Dome and raid fights). Do not",
             "-- edit: measure again and rebuild. Per spec: power type -> targets -> income a second with no cast of",
             "-- its own (auto-attack Rage, damage-over-time procs, ticking spells).",
             "local _, ns = ...", "ns.Data = ns.Data or {}", "ns.Data.resourceTargets = {"]
    for spec in sorted(table):
        rows = ", ".join("[%d] = %.2f" % (k, v) for k, v in sorted(table[spec].items()))
        lines.append("  %s = { [%d] = { %s } }," % (spec, POWER[spec], rows))
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
