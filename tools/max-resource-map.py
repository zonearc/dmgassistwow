#!/usr/bin/env python3
"""Talents that raise a resource's maximum ("Modify Max Resource (418)" in SimC's SpellDataDump): Deeper Stratagem /
Secret Stratagem +1 combo point each. The offline game capped Subtlety at 5 combo points while its talents give 7, so
the offline player and the APL disagreed about when to spend (owner, 2026-11-15: fix the offline game so problems
are found before the game).

Writes tests/max_resource.lua: { [talentSpellID] = { [powerType] = amount } }.
Usage: python3 tools/max-resource-map.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(ROOT, ".libraries", "simc", "midnight", "SpellDataDump", "allspells.txt")
OUT = os.path.join(ROOT, "tests", "max_resource.lua")
POWER = {"mana": 0, "rage": 1, "focus": 2, "energy": 3, "combo_points": 4, "runic_power": 6, "soul_shard": 7,
         "astral_power": 8, "holy_power": 9, "maelstrom": 11, "chi": 12, "insanity": 13, "arcane_charges": 16,
         "fury": 17, "essence": 19}
DIV = {1: 10, 6: 10, 7: 10, 8: 10, 13: 100}


def main():
    out = {}
    sid = None
    lines = open(SRC, encoding="utf-8", errors="replace").read().splitlines()
    for i, line in enumerate(lines):
        m = re.match(r"^Name\s*:\s*.+? \(id=(\d+)\)", line)
        if m:
            sid = int(m.group(1))
            continue
        if "Modify Max Resource (418)" in line and sid:
            v = re.search(r"Base Value: (-?\d+).*?Resource: (\w+)", lines[i + 1])
            if v and v.group(2) in POWER:
                pt = POWER[v.group(2)]
                amount = int(v.group(1)) / DIV.get(pt, 1)
                if amount:
                    out.setdefault(sid, {})[pt] = out.get(sid, {}).get(pt, 0) + amount
    with open(OUT, "w") as f:
        f.write("-- Generated by tools/max-resource-map.py from SimC's SpellDataDump: talents that raise a maximum.\n")
        f.write("return {\n")
        for s in sorted(out):
            f.write("  [%d] = { %s },\n" % (s, ", ".join("[%d] = %g" % (k, v) for k, v in sorted(out[s].items()))))
        f.write("}\n")
    print("%d spells raise a maximum -> %s" % (len(out), OUT))


if __name__ == "__main__":
    main()
