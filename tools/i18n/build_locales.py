#!/usr/bin/env python3
"""Build addons/DMGAssist/Locales/<locale>.lua from tools/i18n/keys.json + tools/i18n/<locale>.txt.

keys.json: the English text of every player-facing line (sorted). <locale>.txt: "<index>\t<translation>" per line,
indexes into keys.json; a missing index falls back to English in game. Checks that every translation keeps the
English line's %s / %d placeholders (same order) and colour codes, and fails otherwise.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = ROOT / "tools" / "i18n"
OUT = ROOT / "addons" / "DMGAssist" / "Locales"
FMT = re.compile(r"%[-0-9.]*[sdif]")
COLOR = re.compile(r"\|c[0-9a-fA-F]{8}|\|r")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    keys = json.loads((HERE / "keys.json").read_text(encoding="utf-8"))
    OUT.mkdir(exist_ok=True)
    bad = 0
    for path in sorted(HERE.glob("*.txt")):
        locale = path.stem
        lines = {}
        for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if not raw.strip():
                continue
            idx, _, text = raw.partition("\t")
            i = int(idx)
            en = keys[i]
            text = text.replace("\\n", "\n")
            if FMT.findall(en) != FMT.findall(text):
                print(f"{locale}:{n} placeholders differ: {en!r} -> {text!r}")
                bad += 1
            if sorted(COLOR.findall(en)) != sorted(COLOR.findall(text)):
                print(f"{locale}:{n} colour codes differ: {en!r} -> {text!r}")
                bad += 1
            lines[en] = text
        out = [f"-- {locale}: generated by tools/i18n/build_locales.py from tools/i18n/{locale}.txt. Edit that file.",
               "local _, ns = ...", "ns.LOCALE_DATA = ns.LOCALE_DATA or {}", f"ns.LOCALE_DATA.{locale} = {{"]
        for en in keys:
            if en in lines:
                out.append(f"  [{lua_str(en)}] = {lua_str(lines[en])},")
        out.append("}")
        (OUT / f"{locale}.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
        print(f"{locale}: {len(lines)}/{len(keys)} lines")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
