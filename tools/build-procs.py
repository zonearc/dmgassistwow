#!/usr/bin/env python3
"""The offline game's procs, per spec: tests/procs.lua, from

  - data/proc-rates.json (tools/wcl-procs.py): how often each buff comes up in top players' raid fights;
  - data/proc-map.json (tools/proc-map.py): which auras make spells free or instant (game data);
  - data/overrides.json (tools/override-map.py): which auras swap a button (Rushing Wind Kick, Ravage).

A proc is kept for a spec when it acts on one of the spec's spells and isn't one of the spec's own casts (a buff you
cast, Metamorphosis, is not random: its swap follows the cast). Rate = applications per second in the logs.
Usage: python3 tools/build-procs.py
"""
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DATA = os.path.join(ROOT, "addons", "DMGAssist", "Data", "midnight")
OUT = os.path.join(ROOT, "tests", "procs.lua")


def spec_spells(spec):
    t = open(os.path.join(DATA, spec + ".lua"), encoding="utf-8").read()
    i = t.find("spellInfo = {")
    ids, cast = set(), set()
    for sid, body in re.findall(r"\n    \[(\d+)\] = \{(.*?)\n    \},", t[i:], re.S):
        ids.add(int(sid))
        if re.search(r"\n      (gcd|ct|cd) = ", body) and "pas = true" not in body:
            cast.add(int(sid))
    return ids, cast


def main():
    rates = json.load(open(os.path.join(ROOT, "data", "proc-rates.json")))
    tp = os.path.join(ROOT, "data", "proc-triggers.json")
    trig = json.load(open(tp)) if os.path.exists(tp) else {}
    affects = json.load(open(os.path.join(ROOT, "data", "aura-affects.json")))
    pmap = json.load(open(os.path.join(ROOT, "data", "proc-map.json")))
    swaps = json.load(open(os.path.join(ROOT, "data", "overrides.json")))
    lines = ["-- Generated by tools/build-procs.py (Warcraft Logs rates x game data). Do not edit.",
             "-- luacheck: no max line length",
             "-- spec -> { { aura, rate (background, per second), d, stacks, free / instant / swap / resets = {ids},",
             "--   by = { [castID] = chance per cast } } }",
             "return {"]
    for spec in sorted(rates):
        if not os.path.exists(os.path.join(DATA, spec + ".lua")):
            continue
        ids, cast = spec_spells(spec)
        rows = []
        tr = trig.get(spec, {})
        resets = {int(k): [x for x in v if x in ids] for k, v in tr.get("resets", {}).items()}
        # weighed with the game data: an aura that acts on the spell (Gore lists Mangle) and comes before most of its
        # early casts, more than before on-time ones (Mangle is cast early so often there are few on-time casts)
        for cid, cands in tr.get("candidates", {}).items():
            c = int(cid)
            if c not in ids or any(c in v for v in resets.values()):
                continue
            for aura, (share, ok) in sorted(cands.items(), key=lambda kv: -kv[1][0]):
                if share >= 0.5 and share >= 1.2 * ok and c in affects.get(aura, []):
                    resets.setdefault(int(aura), []).append(c)
                    break
        auras = dict(rates[spec]["auras"])
        for k in resets:
            auras.setdefault(str(k), {"perMin": 0.0001})
        for aura, r in sorted(auras.items(), key=lambda kv: int(kv[0])):
            a = int(aura)
            if a in cast or r["perMin"] <= 0:
                continue
            # what brings it: per cast of a spell + a background rate (tools/wcl-triggers.py); else by time only
            t_ = tr.get("procs", {}).get(aura)
            by = {int(c): v for c, v in (t_ or {}).get("by", {}).items() if int(c) in ids}
            rate = t_["bg"] if t_ else r["perMin"] / 60.0
            rs = resets.get(a, [])
            m = pmap.get(aura)
            free = [x for x in (m or {}).get("free", []) if x in ids]
            inst = [x for x in (m or {}).get("instant", []) if x in ids]
            sw = sorted({s["override"] for s in swaps if s["aura"] == a and s["override"] in ids
                         and not (set(s["triggers"]) & cast)})
            if not (free or inst or sw or rs):
                continue
            d = (m or {}).get("d") or next((s["duration"] for s in swaps if s["aura"] == a), 10)
            rows.append("    { aura = %d, rate = %.4f, d = %g, stacks = %d, free = { %s }, instant = { %s }, swap = { %s },"
                        " resets = { %s }, by = { %s } }," % (
                            a, rate, d, (m or {}).get("stacks", 1), ", ".join(map(str, free)),
                            ", ".join(map(str, inst)), ", ".join(map(str, sw)), ", ".join(map(str, rs)),
                            ", ".join("[%d] = %.3f" % (c, v) for c, v in sorted(by.items()))))
        if rows:
            lines.append("  %s = {" % spec)
            lines += rows
            lines.append("  },")
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("-> %s" % OUT)


if __name__ == "__main__":
    main()
