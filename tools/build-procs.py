#!/usr/bin/env python3
"""The offline game's procs, per spec: tests/procs.lua, from

  - data/proc-rates.json (tools/wcl-procs.py): how often each buff comes up in top players' raid fights;
  - data/proc-map.json (tools/proc-map.py): which auras make spells free or instant (game data);
  - data/overrides.json (tools/override-map.py): which auras swap a button (Rushing Wind Kick, Ravage).

A proc is kept for a spec when it acts on one of the spec's spells and isn't one of the spec's own casts (a buff you
cast, Metamorphosis, is not random: its swap follows the cast). Rate = applications per second in the logs.
Usage: python3 tools/build-procs.py
"""
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DATA = os.path.join(ROOT, "addons", "DMGAssist", "Data", "midnight")
OUT = os.path.join(ROOT, "tests", "procs.lua")
GLOWS = os.path.join(ROOT, "addons", "DMGAssist", "Data", "ProcGlows.lua")
CASTAURAS = os.path.join(ROOT, "addons", "DMGAssist", "Data", "CastAuras.lua")


def spec_spells(spec):
    t = open(os.path.join(DATA, spec + ".lua"), encoding="utf-8").read()
    i = t.find("spellInfo = {")
    ids, cast = set(), set()
    for sid, body in re.findall(r"\n    \[(\d+)\] = \{(.*?)\n    \},", t[i:], re.S):
        ids.add(int(sid))
        if re.search(r"\n      (gcd|ct|cd) = ", body) and "pas = true" not in body:
            cast.add(int(sid))
    return ids, cast


def spec_names(spec):
    t = open(os.path.join(DATA, spec + ".lua"), encoding="utf-8").read()
    i = t.find("spellInfo = {")
    return {int(a): b for a, b in re.findall(r'\n    \[(\d+)\] = \{[^}]*?n = "(\w+)"', t[i:], re.S)}


def spec_auras(spec):
    """aura id -> token for buffs the spec's lists check (buff.X.up/react/stack/remains)"""
    t = open(os.path.join(DATA, spec + ".lua"), encoding="utf-8").read()
    refs = set(re.findall(r"buff\.(\w+)\.(?:up|react|stack|remains|down)", t))
    out = {}
    for tok, body in re.findall(r"\n    (\w+) = \{\n      a = \{([^}]*)\}", t):
        if tok in refs:
            for x in re.findall(r"\d+", body):
                out.setdefault(int(x), tok)
    return out


def main():
    rates = json.load(open(os.path.join(ROOT, "data", "proc-rates.json")))
    tp = os.path.join(ROOT, "data", "proc-triggers.json")
    trig = json.load(open(tp)) if os.path.exists(tp) else {}
    affects = json.load(open(os.path.join(ROOT, "data", "aura-affects.json")))
    pmap = json.load(open(os.path.join(ROOT, "data", "proc-map.json")))
    swaps = json.load(open(os.path.join(ROOT, "data", "overrides.json")))
    glows, castauras = {}, {}
    lines = ["-- Generated by tools/build-procs.py (Warcraft Logs rates x game data). Do not edit.",
             "-- luacheck: no max line length",
             "-- spec -> { { aura, rate (background, per second), d, stacks, free / instant / swap / resets = {ids},",
             "--   by = { [castID] = chance per cast } } }",
             "return {"]
    for spec in sorted(rates):
        if not os.path.exists(os.path.join(DATA, spec + ".lua")):
            continue
        ids, cast = spec_spells(spec)
        checked = spec_auras(spec)
        names = spec_names(spec)
        rows = []
        tr = trig.get(spec, {})
        resets = {int(k): [x for x in v if x in ids] for k, v in tr.get("resets", {}).items()}
        # weighed with the game data: an aura that acts on the spell (Gore lists Mangle) and comes before most of its
        # early casts, more than before on-time ones (Mangle is cast early so often there are few on-time casts)
        for cid, cands in tr.get("candidates", {}).items():
            c = int(cid)
            if c not in ids or any(c in v for v in resets.values()):
                continue
            for aura, (share, ok) in sorted(cands.items(), key=lambda kv: -kv[1][0]):
                if share >= 0.5 and share >= 1.2 * ok and c in affects.get(aura, []):
                    resets.setdefault(int(aura), []).append(c)
                    break
        auras = dict(rates[spec]["auras"])
        for k in resets:
            auras.setdefault(str(k), {"perMin": 0.0001})
        for aura, r in sorted(auras.items(), key=lambda kv: int(kv[0])):
            a = int(aura)
            if a in cast or r["perMin"] <= 0:
                continue
            # what brings it: per cast of a spell + a background rate (tools/wcl-triggers.py); else by time only
            t_ = tr.get("procs", {}).get(aura)
            by = {int(c): v for c, v in (t_ or {}).get("by", {}).items() if int(c) in ids}
            if a in checked and t_:
                # only from casts (no background, no cast that brings it now and then): then "never applied" means
                # down; Clearcasting from Touch of the Magi every time but also from anything at random isn't
                secs = tr.get("seconds") or 1
                only = t_["bg"] * secs < 0.15 * max(1, t_["n"]) and not any(0.1 < v < 0.9 for v in by.values())
                for c, v in by.items():
                    if v >= 0.9 and c in cast:
                        castauras.setdefault(spec, {})[c] = (checked[a], a, only, max(1, int(round(v))))
            rate = t_["bg"] if t_ else r["perMin"] / 60.0
            rs = resets.get(a, [])
            m = pmap.get(aura)
            free = [x for x in (m or {}).get("free", []) if x in ids]
            inst = [x for x in (m or {}).get("instant", []) if x in ids]
            sw = sorted({s["override"] for s in swaps if s["aura"] == a and s["override"] in ids
                         and not (set(s["triggers"]) & cast)})
            # what lights up while it's up: the spells it acts on (game data) - the proc glow the addon reads
            glow = sorted({x for x in affects.get(aura, []) if x in ids} | set(free) | set(inst))
            if not (free or inst or sw or rs or (a in checked and glow)):
                continue
            # (a proc lights one to a few buttons; a buff your own cast brings - Arcane Surge from Arcane Surge - isn't
            # a proc, and one acting on a dozen spells isn't a glow)
            own = any(v >= 0.9 and names.get(c) == checked.get(a) for c, v in by.items())
            if own or len(glow) > 4:
                glow = sorted(set(free) | set(inst))
                if not (free or inst or sw or rs):
                    continue
            if glow and a in checked:
                glows.setdefault(spec, {})[a] = (checked[a], glow)
            d = (m or {}).get("d") or next((s["duration"] for s in swaps if s["aura"] == a), 10)
            rows.append("    { aura = %d, rate = %.4f, d = %g, stacks = %d, free = { %s }, instant = { %s }, swap = { %s },"
                        " resets = { %s }, by = { %s }, glow = { %s } }," % (
                            a, rate, d, (m or {}).get("stacks", 1), ", ".join(map(str, free)),
                            ", ".join(map(str, inst)), ", ".join(map(str, sw)), ", ".join(map(str, rs)),
                            ", ".join("[%d] = %.3f" % (c, v) for c, v in sorted(by.items())),
                            ", ".join(map(str, glow))))
        if rows:
            lines.append("  %s = {" % spec)
            lines += rows
            lines.append("  },")
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    # cast -> buff it always brings (the logs: Marrowrend -> Bone Shield every time; the data has no link, SimC
    # applies it in code): the addon starts the buff's clock on the cast and knows it's down when never applied
    with open(CASTAURAS, "w") as f:
        f.write("-- Generated by tools/build-procs.py from Warcraft Logs (a buff applied after 90%+ of a spell's casts).\n"
                "-- Do not edit. spec -> { [castID] = { token, auraID, onlyFromCasts, applications per cast } }\n-- luacheck: no max line length\n")
        f.write("local _, ns = ...\nns.Data = ns.Data or {}\nns.Data.castAuras = {\n")
        for spec in sorted(castauras):
            f.write("  %s = {\n" % spec)
            for c, (tok, a, only, n) in sorted(castauras[spec].items()):
                f.write("    [%d] = { \"%s\", %d, %s, %d },\n" % (c, tok, a, "true" if only else "false", n))
            f.write("  },\n")
        f.write("}\n")
    # the addon's copy: per spec, proc buff -> its token and the spells that light up while it's up (Clues seeds its
    # glow links with it: Arcane Missiles glowing = Clearcasting up, no glow = down)
    with open(GLOWS, "w") as f:
        f.write("-- Generated by tools/build-procs.py from the game data (aura -> spells it acts on) and Warcraft Logs (the\n"
                "-- buffs that come up at random). Do not edit. spec -> { [auraID] = { token, { spellIDs that glow } } }\n"
                "-- luacheck: no max line length\n")
        f.write("local _, ns = ...\nns.Data = ns.Data or {}\nns.Data.procGlows = {\n")
        for spec in sorted(glows):
            f.write("  %s = {\n" % spec)
            for a, (tok, g) in sorted(glows[spec].items()):
                f.write("    [%d] = { \"%s\", { %s } },\n" % (a, tok, ", ".join(map(str, g))))
            f.write("  },\n")
        f.write("}\n")
    print("-> %s" % OUT)


if __name__ == "__main__":
    main()
