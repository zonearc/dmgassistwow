#!/usr/bin/env python3
"""Buttons that turn into another spell for a while, from SimC's SpellDataDump (the game data).

An aura with "Override Action Spell (332)" swaps a button: Metamorphosis (20 s) turns Blade Dance into Death Sweep
and Chaos Strike into Annihilation. The offline game (tests/test_scenarios.lua) used to hold every such spell as a
button of its own, castable at any time - Havoc's Death Sweep was offered outside Metamorphosis offline, which the
game never allows (owner, 2026-11-15: "fix it in sims so we are forced to fix it before it goes in game").

Writes data/overrides.json: [{aura, name, duration, triggers: [spell ids whose cast applies it], base: [ids],
override: id}]. Only auras with a duration (a passive talent's swap is permanent: the button just is the other
spell). Usage: python3 tools/override-map.py [.libraries/simc/midnight/SpellDataDump/allspells.txt]
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, ".libraries", "simc", "midnight", "SpellDataDump", "allspells.txt")
OUT = os.path.join(ROOT, "data", "overrides.json")
LUA = os.path.join(ROOT, "addons", "DMGAssist", "Data", "Overrides.lua")
HEAD = re.compile(r"^Name\s*:\s*(.+?) \(id=(\d+)\)")


def blocks(text):
    cur = []
    for line in text.splitlines():
        if HEAD.match(line) and cur:
            yield cur
            cur = []
        cur.append(line)
    if cur:
        yield cur


def main():
    text = open(sys.argv[1] if len(sys.argv) > 1 else SRC, encoding="utf-8", errors="replace").read()
    names = {int(m.group(2)): m.group(1) for m in (HEAD.match(line) for line in text.splitlines()) if m}
    out = []
    for b in blocks(text):
        m = HEAD.match(b[0])
        if not m:
            continue
        name, aid = m.group(1), int(m.group(2))
        dur = 0.0
        triggers = {aid}
        for line in b:
            d = re.match(r"^Duration\s*:\s*([\d.]+) seconds", line)
            if d:
                dur = float(d.group(1))
            t = re.match(r"^Triggered By\s*:\s*(.*)$", line)
            if t:
                triggers |= {int(x) for x in re.findall(r"\((\d+)\)", t.group(1))}
        if dur <= 0:
            continue
        for i, line in enumerate(b):
            if "Override Action Spell" not in line:
                continue
            nxt = " ".join(b[i + 1:i + 4])
            ov = re.search(r"Base Value: (\d+)", nxt)
            if not ov or int(ov.group(1)) == 0:
                continue
            base = set()
            mv = re.search(r"\| Misc Value: (\d+)", nxt)
            if mv and int(mv.group(1)) > 0:
                base.add(int(mv.group(1)))
            aff = re.search(r"Affected Spells: ([^\n]*?)(?:Family Flags|$)", nxt)
            if aff:
                base |= {int(x) for x in re.findall(r"\((\d+)\)", aff.group(1))}
            ovr = int(ov.group(1))
            # not a swap: a spell "swapping" with its own name only (Surging Totem, Halo), or a cast whose own aura
            # names itself (Voidform) - those are buttons of their own
            if not base or aid == ovr or all(names.get(x) == names.get(ovr) for x in base):
                continue
            if base:
                out.append({"aura": aid, "name": name, "duration": dur, "triggers": sorted(triggers),
                            "base": sorted(base), "override": int(ov.group(1))})
    json.dump(out, open(OUT, "w"), indent=1, sort_keys=True)
    open(OUT, "a").write("\n")
    # the addon's copy (and the offline game's): only swaps into a spell some spec's data knows
    known = set()
    for f in glob.glob(os.path.join(ROOT, "addons", "DMGAssist", "Data", "midnight", "*_*.lua")):
        known |= {int(x) for x in re.findall(r"\n    \[(\d+)\] = \{", open(f, encoding="utf-8").read())}
    with open(LUA, "w") as f:
        f.write("-- Generated by tools/override-map.py from SimC's SpellDataDump. Do not edit. Buttons an aura swaps\n"
                "-- for a while (Metamorphosis: Blade Dance -> Death Sweep, 20 s). The swapped-in spell is only castable\n"
                "-- while the aura is up: the game's \"not usable\" for it is never overruled (Engine).\n")
        f.write("local _, ns = ...\nns.Data = ns.Data or {}\nns.Data.overrides = {\n")
        for s in out:
            if s["override"] not in known:
                continue
            f.write("  { aura = %d, duration = %g, override = %d, triggers = { %s }, base = { %s } },\n" % (
                s["aura"], s["duration"], s["override"], ", ".join(map(str, s["triggers"])),
                ", ".join(map(str, s["base"]))))
        f.write("}\n")
    print("%d button swaps with a duration -> %s" % (len(out), OUT))


if __name__ == "__main__":
    main()
