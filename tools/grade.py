#!/usr/bin/env python3
"""Grade DMGAssist's rotation against the per-spec reference (data/reference/<spec>.json, tools/simc-reference.py).

For every spec with a reference: the offline tester (tests/test_scenarios.lua, SCEN_GRADE) runs the real addon with
the reference's talents and a real resource model at 1 and 5 targets, pressing whatever slot 1 shows when it can.
Its casts per minute are compared spell by spell with the reference's:

  match   overlap of the spell mixes (each spell's share of all casts): 100% = the same spells in the same
          proportions; per target count. Throughput (casts per minute) is shown apart: the offline world's
          energy and procs are simpler than SimC's
  gaps    the spells with the largest difference, so a fix knows where to look

Writes docs/coverage/grade.md and prints a summary. --fail-under N exits non-zero when any spec's match drops under
N (for check.sh once the numbers settle).

Usage: python3 tools/grade.py [--specs druid_balance,...] [--fight 120]
"""
import argparse
import glob
import json
import os
import re
import subprocess
import tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REF = os.path.join(ROOT, "data", "reference")
OUT = os.path.join(ROOT, "docs", "coverage", "grade.md")


def token(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower().replace("'", "")).strip("_")


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def talents_file(refs):
    lines = ["return {"]
    for spec, r in sorted(refs.items()):
        hero = next((token(t["name"]) for t in r["talents"] if t["tree"] == "heroTree"), None)
        lines.append("  [%s] = { heroTree = %s, talents = {" % (lua_str(spec), lua_str(hero) if hero else "nil"))
        for t in r["talents"]:
            if t.get("id"):
                lines.append("    { name = %s, spellID = %d, rank = %d }," % (lua_str(t["name"]), t["id"], t["rank"]))
        lines.append("  } },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def run(specs, fight):
    refs = {s: json.load(open(os.path.join(REF, s + ".json"))) for s in specs}
    with tempfile.NamedTemporaryFile("w", suffix=".lua", delete=False) as f:
        f.write(talents_file(refs))
        path = f.name
    env = dict(os.environ, SCEN_GRADE=path, SCEN_FIGHT=str(fight))
    ours = {}
    for spec in specs:
        out = subprocess.run(["lua5.1", "tests/test_scenarios.lua", spec], cwd=ROOT, env=env, capture_output=True,
                             text=True).stdout
        for m in re.finditer(r"^GRADE (\S+) (\d+) (\d+) errors=(\d+) ?(.*)$", out, re.M):
            if m.group(1) != spec:
                continue
            secs = float(m.group(3))
            cast = dict((kv.split("=")[0], int(kv.split("=")[1])) for kv in m.group(5).split() if "=" in kv)
            ours.setdefault(spec, {})[m.group(2)] = {"cpm": {k: v * 60 / secs for k, v in cast.items()},
                                                    "errors": int(m.group(4))}
    os.unlink(path)
    return refs, ours


def shares(c):
    total = sum(c.values()) or 1
    return {k: v / total for k, v in c.items()}


def score(a, b):
    """overlap of the two spell mixes: each spell's share of all casts (priorities, not throughput: the offline
    world's energy and procs are simpler than SimC's)"""
    a, b = shares(a), shares(b)
    keys = set(a) | set(b)
    hi = sum(max(a.get(k, 0), b.get(k, 0)) for k in keys)
    return 100.0 * sum(min(a.get(k, 0), b.get(k, 0)) for k in keys) / hi if hi else 0.0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--specs")
    ap.add_argument("--fight", type=int, default=120)
    ap.add_argument("--fail-under", type=float)
    args = ap.parse_args()
    specs = args.specs.split(",") if args.specs else sorted(
        os.path.basename(p)[:-5] for p in glob.glob(os.path.join(REF, "*.json")))
    refs, ours = run(specs, args.fight)
    rows, worst = [], 100.0
    md = ["# Rotation grade", "", "DMGAssist (offline tester, reference talents, real resources) against the "
          "reference (SimC, same talents). match = overlap of the spell mixes (100% = same spells in the same "
          "proportions). pace = our casts per minute / the reference's. "
          "Generated by tools/grade.py.", "", "| Spec | 1 target | 5 targets | pace 1 / 5 | Biggest gaps (ours / reference, per minute) |",
          "|---|---|---|---|---|"]
    for spec in specs:
        r, o = refs[spec], ours.get(spec, {})
        cells, gaps, pace = [], [], []
        for tg in ("1", "5"):
            ref = r["targets"].get(tg, {}).get("cpm", {})
            mine = o.get(tg, {}).get("cpm", {})
            if not ref:
                cells.append("-")
                continue
            s = score(mine, ref)
            worst = min(worst, s)
            cells.append("%.0f%%" % s)
            pace.append("%.0f%%" % (100.0 * sum(mine.values()) / (sum(ref.values()) or 1)))
            for k in set(ref) | set(mine):
                d = mine.get(k, 0) - ref.get(k, 0)
                if abs(d) >= 1:
                    gaps.append((abs(d), "%s %s: %.1f / %.1f" % (tg, k, mine.get(k, 0), ref.get(k, 0))))
        gaps.sort(reverse=True)
        rows.append((spec, cells))
        md.append("| %s | %s | %s | %s | %s |" % (spec, cells[0], cells[1], " / ".join(pace),
                                                 "; ".join(g for _, g in gaps[:4])))
        print("%-26s 1: %-5s 5: %-5s pace %-10s %s" % (spec, cells[0], cells[1], "/".join(pace),
                                                     "; ".join(g for _, g in gaps[:3])))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(md) + "\n")
    if args.fail_under is not None and worst < args.fail_under:
        raise SystemExit("a spec's match is under %.0f%%" % args.fail_under)


if __name__ == "__main__":
    main()
